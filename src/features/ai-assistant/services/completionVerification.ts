export interface AgentCompletionEvidence {
  kind: 'action' | 'observation' | 'validation' | 'audit'
  scope: AgentVerificationScope
  summary: string
  message: string
}

export interface CompletionVerificationVerdict {
  ok: boolean
  message: string
  checks: CompletionVerificationCheck[]
}

export type CompletionVerificationCheckStatus = 'pass' | 'fail' | 'unknown'

export interface CompletionVerificationCheck {
  requirement: string
  status: CompletionVerificationCheckStatus
  /** One-based ids from the bounded evidence packet. */
  evidence: number[]
}

interface CompletionVerificationPacketOptions {
  userRequest: string
  taskContext?: string
  candidateExplanation: string
  plan: AgentPlanItem[]
  evidence: AgentCompletionEvidence[]
  tokenEstimator: AgentTokenEstimator
}

interface AppliedRobotVerificationMessageOptions {
  userRequest: string
  liveRobot: RobotData
  structuralValidation: string
  lang: Language
  tokenEstimator: AgentTokenEstimator
}

