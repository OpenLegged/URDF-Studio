export const MAX_COMPLETION_EVIDENCE = 12
export const MAX_COMPLETION_CHECKS = 12

/**
 * Add a harness-owned process audit to the verifier packet. The model cannot
 * operate URDF Studio except through registered app capabilities, so counting
 * every attempted app-scope tool call gives direct evidence for requests such
 * as "do not operate the webpage UI" without adding another model-facing tool.
 */
export function appendCompletionRuntimeAudit(
  evidence: AgentCompletionEvidence[],
  appUiToolCalls: number,
): AgentCompletionEvidence[] {
  return [
    ...evidence,
    {
      kind: 'audit',
      scope: 'app',
      summary: 'complete harness runtime action audit',
      message: JSON.stringify({
        complete: true,
        appUiToolCalls: Math.max(0, Math.trunc(appUiToolCalls)),
      }),
    },
  ]
}

/**
 * Keep final-state observations/validations ahead of action receipts. This
 * gives a multi-requirement verifier the widest proof coverage without growing
 * the packet with the full tool transcript.
 */
export function selectCompletionEvidence(
  evidence: AgentCompletionEvidence[],
): AgentCompletionEvidence[] {
  const indexed = evidence.map((item, index) => ({ item, index }))
  const proof = indexed.filter(entry => entry.item.kind !== 'action')
  const selectedProof = proof.slice(-MAX_COMPLETION_EVIDENCE)
  const actionSlots = MAX_COMPLETION_EVIDENCE - selectedProof.length
  const selectedActions = actionSlots > 0
    ? indexed.filter(entry => entry.item.kind === 'action').slice(-actionSlots)
    : []
  return [...selectedActions, ...selectedProof]
    .sort((left, right) => left.index - right.index)
    .map(entry => entry.item)
}

function clip(
  text: string | undefined,
  budget: number,
  estimator: AgentTokenEstimator,
): string {
  return clipAgentTextToTokens(text?.trim() ?? '', budget, estimator)
}

export function buildCompletionVerificationMessages(
  options: CompletionVerificationPacketOptions,
): Array<{ role: 'system' | 'user'; content: string }> {
  const estimator = options.tokenEstimator
  const selectedEvidence = selectCompletionEvidence(options.evidence)
  const packet = {
    userRequest: clip(options.userRequest, 512, estimator),
    taskContext: clip(options.taskContext, 384, estimator),
    candidateExplanation: clip(options.candidateExplanation, 256, estimator),
    plan: options.plan.map(item => ({
      status: item.status,
      step: clip(item.step, 64, estimator),
    })),
    evidence: selectedEvidence.map((item, index) => ({
      id: index + 1,
      kind: item.kind,
      scope: item.scope,
      summary: clip(item.summary, 64, estimator),
      message: clip(item.message, 128, estimator),
    })),
  }
  return [
    { role: 'system', content: VERIFIER_SYSTEM_PROMPT },
    { role: 'user', content: JSON.stringify(packet) },
  ]
}

function appliedRobotSnapshot(robot: RobotData): Record<string, unknown> {
  return {
    name: robot.name,
    rootLinkId: robot.rootLinkId,
    links: Object.fromEntries(Object.entries(robot.links).map(([id, link]) => [id, {
      id: link.id,
      name: link.name,
      visual: {
        type: link.visual.type,
        dimensions: link.visual.dimensions,
        origin: link.visual.origin,
      },
      collision: {
        type: link.collision.type,
        dimensions: link.collision.dimensions,
        origin: link.collision.origin,
      },
      inertial: link.inertial
        ? { mass: link.inertial.mass, origin: link.inertial.origin }
        : null,
    }])),
    joints: Object.fromEntries(Object.entries(robot.joints).map(([id, joint]) => [id, {
      id: joint.id,
      name: joint.name,
      type: joint.type,
      parentLinkId: joint.parentLinkId,
      childLinkId: joint.childLinkId,
      origin: joint.origin,
      axis: joint.axis ?? null,
      limit: joint.limit ?? null,
    }])),
  }
}

export function buildAppliedRobotVerificationMessages(
  options: AppliedRobotVerificationMessageOptions,
): Array<{ role: 'system' | 'user'; content: string }> {
  const snapshot = JSON.stringify(appliedRobotSnapshot(options.liveRobot))
  const packet = {
    responseLanguage: options.lang === 'zh' ? 'Chinese' : 'English',
    originalUserRequest: clip(options.userRequest, 512, options.tokenEstimator),
    evidence: [
      {
        id: 1,
        kind: 'observation',
        scope: 'applied-live-robot',
        message: clip(snapshot, 8_192, options.tokenEstimator),
      },
      {
        id: 2,
        kind: 'validation',
        scope: 'applied-live-robot',
        message: clip(options.structuralValidation, 256, options.tokenEstimator),
      },
    ],
  }
  return [
    { role: 'system', content: APPLIED_ROBOT_VERIFIER_SYSTEM_PROMPT },
    { role: 'user', content: JSON.stringify(packet) },
  ]
}

export function parseCompletionVerificationVerdict(
  content: string,
  evidenceCount?: number,
  proofEvidenceIds?: ReadonlySet<number>,
): CompletionVerificationVerdict | null {
  const start = content.indexOf('{')
  const end = content.lastIndexOf('}')
  if (start < 0 || end <= start) return null
  try {
    const candidate = JSON.parse(content.slice(start, end + 1)) as {
      ok?: unknown
      message?: unknown
      checks?: unknown
    }
    if (
      typeof candidate.ok !== 'boolean'
      || typeof candidate.message !== 'string'
      || !Array.isArray(candidate.checks)
      || candidate.checks.length === 0
      || candidate.checks.length > MAX_COMPLETION_CHECKS
    ) {
      return null
    }
    const message = candidate.message.trim()
    if (!message) return null
    const checks: CompletionVerificationCheck[] = []
    for (const rawCheck of candidate.checks) {
      if (typeof rawCheck !== 'object' || rawCheck === null || Array.isArray(rawCheck)) {
        return null
      }
      const check = rawCheck as Record<string, unknown>
      const requirement = typeof check.requirement === 'string'
        ? check.requirement.trim()
        : ''
      const status = check.status
      if (
        !requirement
        || (status !== 'pass' && status !== 'fail' && status !== 'unknown')
        || !Array.isArray(check.evidence)
        || check.evidence.length > MAX_COMPLETION_EVIDENCE
      ) {
        return null
      }
      const evidence = [...new Set(check.evidence)]
      if (!evidence.every(id => (
        Number.isSafeInteger(id)
        && Number(id) >= 1
        && (evidenceCount === undefined || Number(id) <= evidenceCount)
      ))) {
        return null
      }
      if (status === 'pass' && evidence.length === 0) return null
      if (
        status === 'pass'
        && proofEvidenceIds
        && !evidence.some(id => proofEvidenceIds.has(Number(id)))
      ) {
        return null
      }
      checks.push({
        requirement: requirement.slice(0, 240),
        status,
        evidence: evidence.map(Number),
      })
    }
    const everyCheckPassed = checks.every(check => check.status === 'pass')
    if (candidate.ok !== everyCheckPassed) return null
    return { ok: candidate.ok, message: message.slice(0, 800), checks }
  } catch {
    return null
  }
}

export function buildMissingCompletionEvidencePrompt(
  scopes: AgentVerificationScope[],
): string {
  const instructions = scopes.map(scope => scope === 'draft'
    ? '- Robot draft: use read_path after the latest edit to read back the exact fields or entities changed.'
    : '- Studio UI: use studio inspect or elements/status after the latest command to read back the resulting state.')
  return [
    'Completion gate: the task cannot finish yet because post-action evidence is missing.',
    ...instructions,
    'Compare the observed values with the original request. If anything is wrong, fix it and inspect again. Only then provide the final answer.',
  ].join('\n')
}

export function buildCompletionRepairPrompt(
  verdict: CompletionVerificationVerdict,
): string {
  const unresolved = verdict.checks
    .filter(check => check.status !== 'pass')
    .slice(0, 6)
    .map(check => `- [${check.status}] ${check.requirement}`)
  return [
    `Completion verification failed: ${verdict.message}`,
    ...(unresolved.length ? ['Unresolved requirements:', ...unresolved] : []),
    'Continue the task, correct every unresolved requirement, then collect fresh post-action evidence before finishing.',
  ].join('\n')
}
